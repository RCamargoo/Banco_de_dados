/*criar uma view para retornar os funcionarios e os seus supermercados*/

CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADO AS 
SELECT 	F.FUN_CNPJ AS "CNPJ",
		F.FUN_NOME AS "NOME DO FUNCI",
		F.FUN_DATA_NASCIMENTO AS "DATA DE NASCIMENTO",
        F.FUN_TELEFONE AS "TEELFONE",
        F.FUN_EMAIL AS "EMAIL",
        F.FUN_CARTEIRA_TRABALHO AS  "CARTEIRA DE TRABALHO",
		F.FUN_BANCO_AGENCIA AS "AGENCIA",
        F.FUN_BANCO_CONTA AS "CONTA", 
        F.FUN_DATA_ADIMICAO AS "DATA DE ADIMIÇÃO",
        F.FUN_JORNADA_TRABALHO AS "JORNADA DE TRABALHO", 
        S.SUP_RASO_SOCIAL AS "NOME DO SUPERMERCADO"
FROM	FUNCIONARIO F
JOIN	SUPERMERCADO S ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT * FROM VW_FUNCIONARIOS_SUPERMERCADOS;

